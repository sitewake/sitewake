// Lists every check that can block a capability's publication and what
// evidence each has of catching a real defect: a recorded module in
// tests/fixtures/capability-modules it refuses, or a failure in the latest
// benchmark reports it produced. Writes benchmark/GATES.md.
//
//   node scripts/benchmark/gate-evidence.mjs [--reports <n>]
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { ARTIFACTS, ROOT, parseFlags } from "./lib.mjs";

const flags = parseFlags();
const read = (path) => readFileSync(join(ROOT, path), "utf8");

// Where each family of checks is written and how its codes are spelled there.
const SOURCES = [
  // Codes are written as plain strings or as template literals with a suffix (`code:name`).
  { family: "module rule", file: "lib/capability-center-v2/javascript-runtime.ts", pattern: /[`"](capability_module_[a-z_]+)(?::\$\{)?/g },
  { family: "quality rule", file: "lib/capability-center-v2/quality.ts", pattern: /code: "([a-z_]+)"/g },
  { family: "contract consistency", file: "lib/capability-center-v2/contract-consistency.ts", pattern: /"((?:condition|required|deterministic)_[a-z_]+)"/g },
];

// Checks demoted to notes: the DEMOTED_*CHECKS tables of the three rule files.
const demoted = new Set(SOURCES.flatMap((source) => [...read(source.file).matchAll(/export const DEMOTED_[A-Z_]*CHECKS[^{]*\{([\s\S]*?)\n\};/g)]
  .flatMap((table) => [...table[1].matchAll(/^\s{2}([a-z_]+): "/gm)].map((match) => match[1]))));
const checks = [];
for (const source of SOURCES) {
  const text = read(source.file);
  for (const code of new Set([...text.matchAll(source.pattern)].map((match) => match[1]))) checks.push({ family: source.family, file: source.file, code });
}

const verdicts = JSON.parse(read("tests/fixtures/capability-modules/verdicts.json"));
const fixtureByCode = {};
for (const [file, verdict] of Object.entries(verdicts)) if (verdict.expected && verdict.expected !== "ok") (fixtureByCode[verdict.expected] ||= []).push(file);

const runsDir = join(ARTIFACTS, "runs");
const reports = existsSync(runsDir)
  ? readdirSync(runsDir).sort().reverse().map((id) => join(runsDir, id, "report.json")).filter((path) => existsSync(path)).slice(0, Number(flags.reports || 2)).map((path) => JSON.parse(readFileSync(path, "utf8")))
  : [];
const benchmarkByCode = {};
for (const report of reports) {
  for (const failure of report.failures || []) {
    const text = `${failure.detail || ""} ${failure.note || ""}`;
    for (const check of checks) if (text.includes(check.code)) (benchmarkByCode[check.code] ||= []).push(`${report.runId}:${failure.taskId}`);
  }
}

const rows = checks.map((check) => {
  const fixtures = fixtureByCode[check.code] || [];
  const benchmark = [...new Set(benchmarkByCode[check.code] || [])];
  const evidence = fixtures.length && benchmark.length ? "fixture + benchmark" : fixtures.length ? "fixture" : benchmark.length ? "benchmark" : "none";
  return { ...check, evidence: demoted.has(check.code) ? `${evidence} → note (demoted)` : evidence, fixtures, benchmark };
});
const counts = rows.reduce((acc, row) => ({ ...acc, [row.evidence]: (acc[row.evidence] || 0) + 1 }), {});

const lines = [
  "# Blocking checks and their evidence",
  "",
  `Generated by \`node scripts/benchmark/gate-evidence.mjs\` on ${new Date().toISOString().slice(0, 10)} from ${reports.length} benchmark report(s)${reports.length ? ` (${reports.map((report) => report.runId).join(", ")})` : ""}.`,
  "",
  "A check earns its place by a recorded module it refuses (`tests/fixtures/capability-modules/verdicts.json`) or a benchmark failure it produced. A check with no evidence is demoted to a note: it is still recorded with the version, it no longer blocks publication. The checks that still block without such evidence guard the page the module runs in (no network, no dynamic code, no unbounded loop, nothing but the source it claims to be); they are not judgments of the capability.",
  "",
  `| Evidence | Checks |`, `| --- | --- |`,
  ...Object.entries(counts).sort((a, b) => b[1] - a[1]).map(([evidence, count]) => `| ${evidence} | ${count} |`),
  "",
  "| Family | Check | Evidence | Where |",
  "| --- | --- | --- | --- |",
  ...rows.sort((a, b) => a.family.localeCompare(b.family) || a.code.localeCompare(b.code)).map((row) => `| ${row.family} | \`${row.code}\` | ${row.evidence} | ${[...row.fixtures, ...row.benchmark].join(", ")} |`),
  "",
];
writeFileSync(join(ROOT, "benchmark", "GATES.md"), lines.join("\n"));
console.log(`${checks.length} checks: ${Object.entries(counts).map(([evidence, count]) => `${count} ${evidence}`).join(", ")} → benchmark/GATES.md`);
