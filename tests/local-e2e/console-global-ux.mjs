import assert from "node:assert/strict";
import { chromium } from "playwright";
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ locale: "zh-CN" });
  const errors = [];
  page.on("pageerror", error => errors.push(error.message));
  const base = await (await fetch("http://localhost:3000/api/site-agents/shop")).json();
  const a = { ...base, id: "ux-a", profile: { ...base.profile, name: "UX 网站 A" } };
  const b = { ...base, id: "ux-b", profile: { ...base.profile, name: "UX 网站 B" } };
  await page.route("**/api/site-agents", r => r.fulfill({ json: { agents: [a, b] } }));
  await page.route("**/api/site-agents/ux-a", r => r.fulfill({ json: a }));
  await page.route("**/api/site-agents/ux-b", r => r.fulfill({ json: b }));
  const fact = (id, goal) => ({ runId: id, goal, status: "completed", outcomeStatus: "unknown", outcomeSummary: "需要核对页面结果", endedAt: "2026-09-05T06:00:00Z" });
  let failDetail = true;
  await page.route("**/session-history?*", async r => {
    const query = new URL(r.request().url()).searchParams.get("query") || "";
    if (query === "slow") await new Promise(resolve => setTimeout(resolve, 1000));
    await r.fulfill({ json: { records: [fact(query || "initial", query || "首个任务")], total: 1 } }).catch(() => undefined);
  });
  await page.route("**/session-history/*", r => failDetail ? r.fulfill({ status: 503, json: {} }) : r.fulfill({ json: { detail: { fact: fact("fast", "已恢复的任务详情"), conversation: [], activityTimeline: [], replayChunks: [] } } }));
  await page.goto("http://localhost:3000/?site=ux-a");
  await page.locator(".sw-site-current").filter({ hasText: "UX 网站 A" }).waitFor();
  const overview = page.getByRole("tab", { name: "概览", exact: true });
  await overview.focus(); await page.keyboard.press("ArrowDown");
  assert.equal(await page.getByRole("tab", { name: "智能体", exact: true }).evaluate(e => e === document.activeElement), true);
  await page.getByRole("tab", { name: "用户会话", exact: true }).click();
  await page.locator(".sw-session-detail-error").waitFor();
  assert.equal(await page.locator(".sw-session-list").getByText("结果待确认", { exact: true }).count(), 1);
  failDetail = false;
  await page.locator(".sw-session-detail-error").getByRole("button", { name: "重新加载" }).click();
  await page.getByRole("heading", { name: "已恢复的任务详情" }).waitFor();
  await page.getByRole("textbox", { name: "搜索用户目标" }).fill("slow");
  await page.waitForTimeout(240);
  await page.getByRole("textbox", { name: "搜索用户目标" }).fill("fast");
  await page.locator(".sw-session-list b").getByText("fast", { exact: true }).waitFor();
  await page.waitForTimeout(1200);
  assert.equal(await page.locator(".sw-session-list b").innerText(), "fast");
  await page.locator(".sw-site-current").click(); await page.keyboard.press("Escape");
  assert.equal(await page.locator(".sw-site-menu").count(), 0);
  await page.locator(".sw-site-current").click(); await page.locator(".sw-topbar").click();
  assert.equal(await page.locator(".sw-site-menu").count(), 0);
  await page.locator(".sw-site-current").click();
  await page.locator(".sw-site-menu").getByRole("button", { name: /UX 网站 B/ }).click();
  await page.waitForURL("**/?site=ux-b&view=sessions");
  assert.equal(await page.getByRole("tab", { name: "用户会话" }).getAttribute("aria-selected"), "true");
  await page.goBack(); await page.waitForURL("**/?site=ux-a&view=sessions");
  await page.goBack(); await page.waitForURL("**/?site=ux-a");
  await page.locator(".sw-site-current").filter({ hasText: "UX 网站 A" }).waitFor();
  await page.locator(".sw-overview-v2").waitFor();
  await page.goForward(); await page.waitForURL("**/?site=ux-a&view=sessions");
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator(".sw-session-page").waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  assert.deepEqual(errors, []);
  console.log("PASS: browser history, preserved workspace, keyboard navigation, menu dismissal, detail retry, unknown outcome and search races.");
} finally { await browser.close(); }
